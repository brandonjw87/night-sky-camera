    private static double[] toB1875;

    /** IAU abbreviation ("UMa") of the constellation a J2000 direction lies in. */
    public static String at(double[] j2000) {
        double[] m = toB1875;
        if (m == null) toB1875 = m = Astro.precession(B1875);
        double[] v = new double[3];
        Rot.apply(m, j2000[0], j2000[1], j2000[2], v);
        double[] rd = Astro.raDec(v);
        double ra = rd[0] / Astro.DEG / 15, dec = rd[1] / Astro.DEG;
        for (int i = 0; i < ABBR.length; i++) {
            if (dec >= ROWS[3 * i + 2] && ra >= ROWS[3 * i] && ra < ROWS[3 * i + 1]) return ABBR[i];
        }
        return "Oct";
    }

